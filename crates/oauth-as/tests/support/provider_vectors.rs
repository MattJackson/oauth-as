pub fn rsa_pkcs8() -> Vec<u8> {
    use base64::Engine;
    use rsa::{pkcs8::EncodePrivateKey, BigUint, RsaPrivateKey};
    let dec = |v: &str| {
        BigUint::from_bytes_be(
            &base64::engine::general_purpose::URL_SAFE_NO_PAD
                .decode(v)
                .unwrap(),
        )
    };
    RsaPrivateKey::from_components(
        dec(N_B64URL),
        dec(E_B64URL),
        dec(D_B64URL),
        vec![dec(P_B64URL), dec(Q_B64URL)],
    )
    .unwrap()
    .to_pkcs8_der()
    .unwrap()
    .as_bytes()
    .to_vec()
}
